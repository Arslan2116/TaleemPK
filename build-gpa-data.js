// Builds gpa-systems.js (window.TPK_GPA) — grade→grade-point scales per university,
// from GPA_Grading_Systems.csv via match-map.json. Keeps a single HEC default and
// only stores per-uni overrides where the scale differs, so the file stays small.
// Run: node build-match-map.js && node build-gpa-data.js
const fs = require('fs');
function parseCSV(t){const rows=[];let row=[],cur='',q=false;for(let i=0;i<t.length;i++){const c=t[i];if(q){if(c==='"'){if(t[i+1]==='"'){cur+='"';i++}else q=false}else cur+=c}else{if(c==='"')q=true;else if(c===','){row.push(cur);cur=''}else if(c==='\n'){row.push(cur);rows.push(row);row=[];cur=''}else if(c==='\r'){}else cur+=c}}if(cur||row.length){row.push(cur);rows.push(row)}return rows;}
function csvObjects(file){const rows=parseCSV(fs.readFileSync(file,'utf8'));const head=rows[0].map(h=>h.replace(/^﻿/,'').trim());return rows.slice(1).filter(r=>r.some(c=>c&&c.trim())).map(r=>{const o={};head.forEach((h,i)=>o[h]=(r[i]||'').trim());return o});}
const num = v => { const n=parseFloat(v); return isNaN(n)?null:n; };

const GRADES = ['A+','A','A-','B+','B','B-','C+','C','C-','D+','D','F'];
const map = JSON.parse(fs.readFileSync('match-map.json','utf8'));            // tpkId -> datasetId
const dsToTpk = {}; Object.entries(map).forEach(([t,d])=>{ dsToTpk[d]=parseInt(t); });
const rows = csvObjects('GPA_Grading_Systems.csv');

function scaleOf(r){
  const g = {};
  GRADES.forEach(k=>{ const gp=num(r[k+'_gp']); if(gp!==null) g[k]=gp; });
  return g;
}
function convFactor(r){
  // most: "Percentage = CGPA × 25"  → factor 25
  const m=(r.percentage_conversion_formula||'').match(/[×x*]\s*([\d.]+)/);
  return m?parseFloat(m[1]):25;
}

// HEC standard = the row with university_id 0 (HEC), else first row
const hecRow = rows.find(r=>r.university_id==='0') || rows[0];
const hec = { grades: scaleOf(hecRow), conv: convFactor(hecRow) };
const hecKey = JSON.stringify(hec.grades);

const overrides = {};
let custom=0;
rows.forEach(r=>{
  const tpk = dsToTpk[parseInt(r.university_id)];
  if(!tpk) return;
  const grades = scaleOf(r);
  if(Object.keys(grades).length < 5) return;             // incomplete
  if(JSON.stringify(grades) === hecKey) return;          // same as HEC default — skip
  overrides[tpk] = { grades, conv: convFactor(r) };
  custom++;
});

const js = `/* AUTO-GENERATED by build-gpa-data.js — university GPA grade-point scales
   (HEC standard default + ${custom} verified custom scales). Keyed by TaleemPK id.
   Use: scale = (window.TPK_GPA.byId[uniId] || window.TPK_GPA.hec). */
window.TPK_GPA = ${JSON.stringify({ hec, byId: overrides })};
`;
fs.writeFileSync('gpa-systems.js', js);
console.log(`Wrote gpa-systems.js — HEC default + ${custom} custom university scales`);
console.log('HEC grades:', JSON.stringify(hec.grades));
