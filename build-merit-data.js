// Builds merit-formulas.js (window.TPK_MERIT) keyed by TaleemPK university id,
// from the verified Kaggle Merit_Formulas.csv via match-map.json.
// Run: node build-match-map.js && node build-merit-data.js
const fs = require('fs');

function parseCSV(text){const rows=[];let row=[],cur='',q=false;for(let i=0;i<text.length;i++){const c=text[i];if(q){if(c==='"'){if(text[i+1]==='"'){cur+='"';i++}else q=false}else cur+=c}else{if(c==='"')q=true;else if(c===','){row.push(cur);cur=''}else if(c==='\n'){row.push(cur);rows.push(row);row=[];cur=''}else if(c==='\r'){}else cur+=c}}if(cur||row.length){row.push(cur);rows.push(row)}return rows;}
function csvObjects(file){const rows=parseCSV(fs.readFileSync(file,'utf8'));const head=rows[0].map(h=>h.replace(/^﻿/,'').trim());return rows.slice(1).filter(r=>r.some(c=>c&&c.trim())).map(r=>{const o={};head.forEach((h,i)=>o[h]=(r[i]||'').trim());return o});}
const num = v => { const n=parseFloat(v); return isNaN(n)?0:n; };

const map = JSON.parse(fs.readFileSync('match-map.json','utf8'));      // tpkId -> datasetId
const formulas = csvObjects('Merit_Formulas.csv');

// group formulas by dataset university_id
const byUni = {};
formulas.forEach(f=>{ const id=parseInt(f.university_id); (byUni[id]=byUni[id]||[]).push(f); });

// pick the PRIMARY formula for a uni: prefer a general UG row with matric+fsc+test,
// avoid A-Level/O-Level-only rows (matric=0 & other>0), prefer sum==100.
function pickPrimary(rows){
  const score = r => {
    const m=num(r['matric_weightage_%']), fs=num(r['fsc_weightage_%']), t=num(r['entry_test_weightage_%']);
    const iv=num(r['interview_weightage_%']), o=num(r['other_weightage_%']);
    const cat=(r.program_category||'').toLowerCase();
    let s=0;
    // Prefer a CS/computing formula as the default (most calculator users are CS
    // applicants), then engineering, then general "all UG".
    if(/\bcs\b|computing|computer/.test(cat)) s+=7;
    else if(/engineering/.test(cat)) s+=5;
    else if(/all|general/.test(cat)) s+=6;
    if(/a-level|o-level|equivalence/.test(cat)) s-=10;       // skip A-level-only
    if(m>0) s+=3;                                            // has matric component (standard FSc path)
    if(Math.abs(m+fs+t+iv+o-100)<0.5) s+=2;                 // weights sum to 100
    if(t>0) s+=1;
    return s;
  };
  return rows.slice().sort((a,b)=>score(b)-score(a))[0];
}

const out = {};
let withFormula=0;
for(const [tpkId, dsId] of Object.entries(map)){
  const rows = byUni[parseInt(dsId)];
  if(!rows || !rows.length) continue;
  const f = pickPrimary(rows);
  const matric=num(f['matric_weightage_%']), fsc=num(f['fsc_weightage_%']), test=num(f['entry_test_weightage_%']);
  const interview=num(f['interview_weightage_%']), other=num(f['other_weightage_%']);
  if(matric===0 && fsc===0 && test===0) continue; // special/no-formula unis (LUMS/IBA SAT-based) — skip
  out[tpkId] = {
    m: matric, f: fsc, t: test,
    iv: interview || undefined,
    o: other || undefined,
    on: (other && f.other_component_name) ? f.other_component_name : undefined,
    test: f.entry_test_name || 'Entry Test',
    cat: f.program_category || undefined,
    min: num(f['min_eligibility_%']) || undefined,
    src: (f.verification_source||'').slice(0,80) || undefined
  };
  // strip undefineds for compact output
  Object.keys(out[tpkId]).forEach(k=>{ if(out[tpkId][k]===undefined) delete out[tpkId][k]; });
  withFormula++;
}

const js = `/* AUTO-GENERATED by build-merit-data.js — verified merit formulas from the
   Kaggle dataset (internet cross-checked). Keyed by TaleemPK university id.
   { m:matric%, f:fsc%, t:test%, iv:interview%, o:other%, on:otherName,
     test:testName, cat:programCategory, min:minEligibility%, src:source } */
window.TPK_MERIT = ${JSON.stringify(out)};
`;
fs.writeFileSync('merit-formulas.js', js);
console.log(`Wrote merit-formulas.js — ${withFormula} universities with verified formulas`);
// quick sanity print of a few known ones
['1','8','9'].forEach(id=>{ if(out[id]) console.log('  tpk#'+id+':', JSON.stringify(out[id])); });
